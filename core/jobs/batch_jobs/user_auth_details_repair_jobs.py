TAG_OK = 'OK'
TAG_ERR = 'ERR'
TAG_PUT = 'PUT'
TAG_EMAIL = 'EMAIL'
TAG_AUTH_ID = 'AUTH_ID'

# NOTE: Firebase accepts any string of 1 to 128 characters as a uid. This
# length is used only so that generated IDs look like the ones Firebase
# generates.
_FIREBASE_AUTH_ID_LENGTH = 28


class RepairMissingUserAuthDetailsJobBase(base_jobs.JobBase):
    """Gives users the auth models that FirebaseServerSyncJob needs.

    A "user" is any user ID that has a UserAuthDetailsModel, a
    UserSettingsModel, or a UserIdByFirebaseAuthIdModel pointing to it. Profiles
    (users whose UserAuthDetailsModel have a parent_user_id) are skipped to stay
    consistent with the FirebaseServerSyncJob.

    After a run with DRY_RUN=False that outputs no errors, every user (that is
    not a profile) has ALL of the following, where USER_ID and FIREBASE_AUTH_ID
    are consistent in all three models:

    1. UserSettingsModel(id=USER_ID) with globally unique email (ignoring case).
    2. UserAuthDetailsModel(id=USER_ID, firebase_auth_id=FIREBASE_AUTH_ID).
    3. UserIdByFirebaseAuthIdModel(id=FIREBASE_AUTH_ID, user_id=USER_ID);
    4. There is no other UserIdByFirebaseAuthIdModel with user_id=USER_ID.
    5. All three models agree on whether the user is deleted.

    FIREBASE_AUTH_ID is the only ID among the user's existing firebase_auth_id
    and UserIdByFirebaseAuthIdModels, or a new one generated by
    `_get_deterministic_auth_id` if they have none (see
    GroupedUserModels.linked_auth_ids).

    The job never creates or changes a UserSettingsModel, and never updates an
    existing firebase_auth_id. Users that break rule 1, whose existing models
    break rule 5, who have more than one Firebase auth ID among their
    firebase_auth_id and UserIdByFirebaseAuthIdModels, or who claim the same
    Firebase auth ID as another user, are reported as errors and left
    unchanged; fix them by hand and rerun the job.

    The job outputs:
        OK <n>: The number of users that already had all three models.
        ERR: <message> (stderr): One line per user that was not fixed.
        PUT <n> / WOULD PUT <n>: The number of models created.

    Attributes:
        DRY_RUN: bool. Whether to only report the fixes without saving them.
    """

    DRY_RUN = True

    def run(self) -> beam.PCollection[job_run_result.JobRunResult]:
        keyed_auth_models = (
            self.pipeline
            | 'Get auth models'
            >> ndb_io.GetModels(
                auth_models.UserAuthDetailsModel.get_all(include_deleted=True)
            )
            | 'Key auth models' >> beam.Map(lambda m: (m.id, m))
        )
        keyed_settings_models = (
            self.pipeline
            | 'Get settings models'
            >> ndb_io.GetModels(
                user_models.UserSettingsModel.get_all(include_deleted=True)
            )
            | 'Key settings models' >> beam.Map(lambda m: (m.id, m))
        )
        keyed_backlink_models = (
            self.pipeline
            | 'Get backlink models'
            >> ndb_io.GetModels(
                auth_models.UserIdByFirebaseAuthIdModel.get_all(
                    include_deleted=True
                )
            )
            | 'Key backlink models' >> beam.Map(lambda m: (m.user_id, m))
        )

        grouped_user_models, all_emails, all_auth_ids = operator.itemgetter(
            TAG_OK, TAG_EMAIL, TAG_AUTH_ID
        )(
            {
                'auth': keyed_auth_models,
                'settings': keyed_settings_models,
                'backlink': keyed_backlink_models,
            }
            | beam.CoGroupByKey()
            | 'Build grouped user models'
            >> beam.FlatMapTuple(_build_grouped_user_models).with_outputs(
                TAG_OK, TAG_EMAIL, TAG_AUTH_ID
            )
        )

        shared_emails = (
            all_emails
            | 'Count emails' >> beam.combiners.Count.PerElement()
            | 'Keep shared emails' >> beam.Filter(lambda kv: kv[1] > 1)
        )

        shared_auth_ids = (
            all_auth_ids
            | 'Count auth ids' >> beam.combiners.Count.PerElement()
            | 'Keep shared auth ids' >> beam.Filter(lambda kv: kv[1] > 1)
        )

        oks, errs, needs_put = operator.itemgetter(TAG_OK, TAG_ERR, TAG_PUT)(
            grouped_user_models
            | 'Diagnose user models'
            >> beam.FlatMap(
                _diagnose_user_models,
                shared_emails=pvalue.AsDict(shared_emails),
                shared_auth_ids=pvalue.AsDict(shared_auth_ids),
            ).with_outputs(TAG_OK, TAG_ERR, TAG_PUT)
        )

        outputs = [
            oks
            | 'Count oks' >> beam.CombineGlobally(sum)
            | 'Format oks' >> beam.Map(lambda num: f'OK {num}')
            | 'To stdout' >> beam.Map(job_run_result.JobRunResult.as_stdout),
            errs
            | 'Format errs' >> beam.Map(lambda msg: f'ERR: {msg}')
            | 'To stderr' >> beam.Map(job_run_result.JobRunResult.as_stderr),
        ]

        if self.DRY_RUN:
            outputs.append(
                needs_put
                | 'Count would-puts'
                >> job_result_transforms.CountObjectsToJobRunResult('WOULD PUT')
            )
        else:
            outputs.append(
                needs_put
                | 'Wait on puts' >> beam.WaitOn(needs_put | ndb_io.PutModels())
                | 'Count puts'
                >> job_result_transforms.CountObjectsToJobRunResult('PUT')
            )

        return outputs | 'Flatten outputs' >> beam.Flatten()


class AuditMissingUserAuthDetailsJob(RepairMissingUserAuthDetailsJobBase):
    """Reports the fixes without saving them."""

    DRY_RUN = True


class RepairMissingUserAuthDetailsJob(RepairMissingUserAuthDetailsJobBase):
    """Saves the fixes to the datastore."""

    DRY_RUN = False


def _build_grouped_user_models(
    user_id: str,
    group_dict: CoGroupByKeyModels,
) -> abc.Iterator[beam.TaggedOutput]:
    """Tags a user's models, unless the user is a profile.

    NOTE: Profiles have no Firebase account, so they need no auth models.

    Args:
        user_id: str. The ID of the user.
        group_dict: CoGroupByKeyModels. The user's models, grouped by kind.

    Yields:
        TaggedOutput. TAG_EMAIL with the user's lowercased email and
        TAG_AUTH_ID with each Firebase auth ID the user claims, whether or not
        the user can be fixed, then TAG_OK with the user's models.
    """
    user = GroupedUserModels.from_group_dict(user_id, group_dict)
    if user.is_profile_user:
        return
    if email := user.email:
        yield beam.TaggedOutput(TAG_EMAIL, email.lower())
    for auth_id in user.linked_auth_ids:
        yield beam.TaggedOutput(TAG_AUTH_ID, auth_id)
    yield beam.TaggedOutput(TAG_OK, user)


def _diagnose_user_models(
    group: GroupedUserModels,
    shared_emails: abc.Mapping[str, int] = types.MappingProxyType({}),
    shared_auth_ids: abc.Mapping[str, int] = types.MappingProxyType({}),
) -> abc.Iterator[beam.TaggedOutput]:
    """Tags users that are OK, have errors, or need to be fixed.

    Args:
        group: GroupedUserModels. The user's models.
        shared_emails: Mapping(str, int). The number of users with each
            lowercased email, for emails that more than one user has.
        shared_auth_ids: Mapping(str, int). The number of users claiming each
            Firebase auth ID (see _build_grouped_user_models), for IDs that
            more than one user claims.

    Yields:
        TaggedOutput. TAG_ERR with the first problem found, if any, and nothing
        else. Otherwise TAG_OK with 1, or TAG_PUT with the new models the user
        is missing, marked as deleted if the user is.
    """
    user_id = group.user_id
    if (email := group.email) is None:
        yield beam.TaggedOutput(
            TAG_ERR,
            f'UserSettingsModel({user_id=}) is missing an email',
        )
    elif email.lower() in shared_emails:
        yield beam.TaggedOutput(
            TAG_ERR,
            f'UserSettingsModel({user_id=}) is sharing an email',
        )
    elif (deleted := group.deleted) is None:
        yield beam.TaggedOutput(
            TAG_ERR,
            f'User({user_id=}) has models that disagree on deletion status',
        )
    elif len(auth_ids := group.linked_auth_ids) >= 2:
        yield beam.TaggedOutput(
            TAG_ERR,
            f'User({user_id=}) is linked with multiple {auth_ids=}',
        )
    elif (auth_id := auth_ids[0]) in shared_auth_ids:
        yield beam.TaggedOutput(
            TAG_ERR,
            f'User({user_id=}) shares {auth_id=} with another user',
        )
    else:
        missing_models: list[base_models.BaseModel] = []
        if not (group.auth_model and group.auth_model.firebase_auth_id):
            missing_models.append(
                _build_missing_auth_model(user_id, auth_id, deleted)
            )
        if not group.backlink_models:
            missing_models.append(
                _build_missing_backlink_model(user_id, auth_id, deleted)
            )
        if not missing_models:
            yield beam.TaggedOutput(TAG_OK, 1)
        for model in missing_models:
            yield beam.TaggedOutput(TAG_PUT, model)


def _build_missing_auth_model(
    user_id: str, auth_id: str, deleted: bool
) -> auth_models.UserAuthDetailsModel:
    """Returns a new UserAuthDetailsModel for the user."""
    with datastore_services.get_ndb_context():
        model = auth_models.UserAuthDetailsModel(
            id=user_id,
            firebase_auth_id=auth_id,
            deleted=deleted,
        )
        model.update_timestamps()
    return model


def _build_missing_backlink_model(
    user_id: str, auth_id: str, deleted: bool
) -> auth_models.UserIdByFirebaseAuthIdModel:
    """Returns a new UserIdByFirebaseAuthIdModel for the user."""
    with datastore_services.get_ndb_context():
        model = auth_models.UserIdByFirebaseAuthIdModel(
            id=auth_id,
            user_id=user_id,
            deleted=deleted,
        )
        model.update_timestamps()
    return model


def _get_deterministic_auth_id(user_id: str) -> str:
    """Returns the ID this job gives a user with no other candidate ID.

    The generated ID is a hash of the user ID, rather than one from Firebase,
    because:

    1. The Firebase Admin SDK can't reserve a uid without creating an account,
       and these jobs must not touch Firebase. FirebaseServerSyncJob creates
       the account later, with whatever uid the UserAuthDetailsModel has.
    2. The same user always gets the same ID, so a rerun after an interrupted
       run creates the same models instead of conflicting ones.

    Args:
        user_id: str. The ID of the user.

    Returns:
        str. The 28-character hash of the user's ID.
    """
    return utils.convert_to_hash(user_id, _FIREBASE_AUTH_ID_LENGTH)


class CoGroupByKeyModels(TypedDict):
    """The models that CoGroupByKey grouped under one user ID.

    NOTE: CoGroupByKey only promises iterables, which may be read only once.

    Attributes:
        auth: Iterable(UserAuthDetailsModel). The user's auth model, if any.
            Its ID is the user ID, so there is at most one.
        settings: Iterable(UserSettingsModel). The user's settings model, if
            any. Its ID is the user ID, so there is at most one.
        backlinks: Iterable(UserIdByFirebaseAuthIdModel). Every model whose
            user_id is the user ID. There can be any number of them, because
            their ID is a Firebase auth ID and the datastore doesn't enforce
            that user_id is unique.
    """

    auth: abc.Iterable[auth_models.UserAuthDetailsModel]
    settings: abc.Iterable[user_models.UserSettingsModel]
    backlink: abc.Iterable[auth_models.UserIdByFirebaseAuthIdModel]


@dataclasses.dataclass(frozen=True, kw_only=True)
class GroupedUserModels:
    """The models that CoGroupByKey grouped under one user ID, read once.

    Attributes:
        user_id: str. The user ID that the models were grouped under.
        auth_model: UserAuthDetailsModel|None. The user's auth model, if any.
        settings_model: UserSettingsModel|None. The user's settings model, if
            any.
        backlink_models: tuple(UserIdByFirebaseAuthIdModel). Every model whose
            user_id is the user ID.
    """

    user_id: str
    auth_model: auth_models.UserAuthDetailsModel | None
    settings_model: user_models.UserSettingsModel | None
    backlink_models: tuple[auth_models.UserIdByFirebaseAuthIdModel, ...]

    @classmethod
    def from_group_dict(
        cls, user_id: str, group_dict: CoGroupByKeyModels
    ) -> GroupedUserModels:
        """Reads the models that CoGroupByKey grouped under the user ID.

        Args:
            user_id: str. The ID of the user.
            group_dict: CoGroupByKeyModels. The user's models, grouped by kind.

        Returns:
            GroupedUserModels. The user's models.
        """
        return cls(
            user_id=user_id,
            auth_model=next(iter(group_dict['auth']), None),
            settings_model=next(iter(group_dict['settings']), None),
            backlink_models=tuple(group_dict['backlink']),
        )

    @property
    def models(self) -> tuple[base_models.BaseModel, ...]:
        """The user's existing models."""
        options = (self.auth_model, self.settings_model, *self.backlink_models)
        return tuple(model for model in options if model is not None)

    @property
    def is_profile_user(self) -> bool:
        """Whether the user is a profile of another user."""
        return bool(self.auth_model and self.auth_model.parent_user_id)

    @property
    def deleted(self) -> bool | None:
        """Whether the user's models are marked as deleted, or None if they
        disagree. Missing models are ignored.
        """
        if len(deleted_values := {bool(m.deleted) for m in self.models}) == 1:
            return deleted_values.pop()
        return None

    @property
    def email(self) -> str | None:
        """The email of the user's UserSettingsModel, or None if missing."""
        return self.settings_model and self.settings_model.email or None

    @property
    def linked_auth_ids(self) -> tuple[str, ...]:
        """The Firebase auth IDs that would sign in as the user, sorted.

        These are the IDs that the user's models hold, deleted or not (since a
        deleted model still holds its ID). A user whose models hold none gets
        the ID that the job would generate for them, so that it is checked for
        collisions with other users' IDs like any other.
        """
        auth_id = self.auth_model and self.auth_model.firebase_auth_id
        backlink_ids = (m.id for m in self.backlink_models)
        return tuple(sorted(i for i in {auth_id, *backlink_ids} if i)) or (
            _get_deterministic_auth_id(self.user_id),
        )
