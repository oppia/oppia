/**
 * @fileoverview Component for display hint modal.
 */

import {Component, OnDestroy} from '@angular/core';
import {NgbActiveModal} from '@ng-bootstrap/ng-bootstrap';
import {RecordedVoiceovers} from 'domain/exploration/recorded-voiceovers.model';
import {SubtitledHtml} from 'domain/exploration/subtitled-html.model';
import {StateCard} from 'domain/state_card/state-card.model';
import {AudioPlayerService} from 'services/audio-player.service';
import {AutogeneratedAudioPlayerService} from 'services/autogenerated-audio-player.service';
import {HintsAndSolutionManagerService} from '../services/hints-and-solution-manager.service';
import {PlayerPositionService} from '../services/player-position.service';
import {PlayerTranscriptService} from '../services/player-transcript.service';
import {VoiceoverPlayerService} from '../services/voiceover-player.service';
import {AudioBarStatusService} from 'services/audio-bar-status.service';
import {AppConstants} from 'app.constants';
import {Subscription} from 'rxjs';

@Component({
  selector: 'oppia-display-hint-modal',
  templateUrl: './display-hint-modal.component.html',
})
export class DisplayHintModalComponent implements OnDestroy {
  // These properties are initialized using Angular lifecycle hooks
  // and we need to do non-null assertion. For more information, see
  // https://github.com/oppia/oppia/wiki/Guide-on-defining-types#ts-7-1.
  index!: number;
  COMPONENT_NAME_HINT!: string;
  hint!: SubtitledHtml;
  displayedCard!: StateCard;
  recordedVoiceovers!: RecordedVoiceovers;
  hintContentId!: string;
  isPlaying: boolean = false;
  hasVoiceover: boolean = false;
  private directiveSubscriptions = new Subscription();

  constructor(
    private ngbActiveModal: NgbActiveModal,
    private audioPlayerService: AudioPlayerService,
    private autogeneratedAudioPlayerService: AutogeneratedAudioPlayerService,
    private hintsAndSolutionManagerService: HintsAndSolutionManagerService,
    private playerPositionService: PlayerPositionService,
    private playerTranscriptService: PlayerTranscriptService,
    private voiceoverPlayerService: VoiceoverPlayerService,
    private audioBarStatusService: AudioBarStatusService
  ) {}

  ngOnInit(): void {
    let displayHint = this.hintsAndSolutionManagerService.displayHint(
      this.index
    );
    if (displayHint === null) {
      throw new Error('Hint not found.');
    }
    this.hint = displayHint;
    this.displayedCard = this.playerTranscriptService.getCard(
      this.playerPositionService.getDisplayedCardIndex()
    );
    let contentId = this.hint.contentId;
    if (contentId === null) {
      throw new Error('Content id not found.');
    }
    this.hintContentId = contentId;

    // Check if voiceover exists for this hint.
    this.voiceoverPlayerService.setActiveVoiceover(this.hintContentId);
    this.voiceoverPlayerService.setActiveComponentName(
      AppConstants.COMPONENT_NAME_HINT
    );
    this.hasVoiceover =
      this.voiceoverPlayerService.getActiveVoiceover() !== undefined;

    this.audioPlayerService.onAutoplayAudio.emit();

    // Subscribe to audio player events.
    this.directiveSubscriptions.add(
      this.audioPlayerService.onAudioStop.subscribe(() => {
        this.isPlaying = false;
      })
    );

    // Subscribe to audio end event.
    this.directiveSubscriptions.add(
      this.audioPlayerService.onAudioEnd.subscribe(() => {
        this.isPlaying = false;
      })
    );
  }

  ngOnDestroy(): void {
    this.directiveSubscriptions.unsubscribe();
  }

  isAudioBarExpanded(): boolean {
    return this.audioBarStatusService.isAudioBarExpanded();
  }

  playVoiceover(): void {
    if (this.isPlaying) {
      // Stop and clear the audio.
      this.audioPlayerService.stop();
      this.audioPlayerService.clear();
      this.isPlaying = false;
    } else {
      if (this.hasVoiceover) {
        // Always load and play from the beginning.
        const voiceover = this.voiceoverPlayerService.getActiveVoiceover();
        if (voiceover) {
          // First stop and clear any existing audio.
          this.audioPlayerService.stop();
          this.audioPlayerService.clear();

          // Then load and play the audio.
          this.audioPlayerService.loadAsync(voiceover.filename).then(() => {
            // Set the current time to 0 before playing.
            this.audioPlayerService.setCurrentTime(0);
            this.audioPlayerService.play();
            this.isPlaying = true;
          });
        }
      }
    }
  }

  closeModal(): void {
    this.audioPlayerService.stop();
    this.autogeneratedAudioPlayerService.cancel();
    this.ngbActiveModal.dismiss('cancel');
  }
}
