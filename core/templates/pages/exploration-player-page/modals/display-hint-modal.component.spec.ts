/**
 * @fileoverview Unit tests for DisplayHintModalComponent.
 */

import {HttpClientTestingModule} from '@angular/common/http/testing';
import {
  ComponentFixture,
  TestBed,
  waitForAsync,
  fakeAsync,
  tick,
} from '@angular/core/testing';
import {NgbActiveModal} from '@ng-bootstrap/ng-bootstrap';
import {SubtitledHtml} from 'domain/exploration/subtitled-html.model';
import {StateCard} from 'domain/state_card/state-card.model';
import {AudioPlayerService} from 'services/audio-player.service';
import {AutogeneratedAudioPlayerService} from 'services/autogenerated-audio-player.service';
import {HintsAndSolutionManagerService} from '../services/hints-and-solution-manager.service';
import {PlayerPositionService} from '../services/player-position.service';
import {PlayerTranscriptService} from '../services/player-transcript.service';
import {DisplayHintModalComponent} from './display-hint-modal.component';
import {MockTranslatePipe} from 'tests/unit-test-utils';
import {Interaction} from 'domain/exploration/InteractionObjectFactory';
import {NO_ERRORS_SCHEMA, EventEmitter} from '@angular/core';
import {VoiceoverPlayerService} from '../services/voiceover-player.service';
import {AudioBarStatusService} from 'services/audio-bar-status.service';
import {AppConstants} from 'app.constants';

describe('Display hint modal', () => {
  let fixture: ComponentFixture<DisplayHintModalComponent>;
  let componentInstance: DisplayHintModalComponent;
  let hintsAndSolutionManagerService: HintsAndSolutionManagerService;
  let playerTranscriptService: PlayerTranscriptService;
  let audioPlayerService: AudioPlayerService;
  let autogeneratedAudioPlayerService: AutogeneratedAudioPlayerService;
  let ngbActiveModal: NgbActiveModal;
  let voiceoverPlayerService: VoiceoverPlayerService;
  let audioBarStatusService: AudioBarStatusService;

  beforeEach(waitForAsync(() => {
    TestBed.configureTestingModule({
      imports: [HttpClientTestingModule],
      declarations: [DisplayHintModalComponent, MockTranslatePipe],
      providers: [
        NgbActiveModal,
        {
          provide: AudioPlayerService,
          useValue: {
            onAutoplayAudio: new EventEmitter(),
            onAudioStop: new EventEmitter(),
            onAudioEnd: new EventEmitter(),
            stop: jasmine.createSpy('stop'),
            clear: jasmine.createSpy('clear'),
            loadAsync: jasmine
              .createSpy('loadAsync')
              .and.returnValue(Promise.resolve()),
            setCurrentTime: jasmine.createSpy('setCurrentTime'),
            play: jasmine.createSpy('play'),
          },
        },
        {
          provide: AutogeneratedAudioPlayerService,
          useValue: {
            cancel: jasmine.createSpy('cancel'),
          },
        },
        {
          provide: HintsAndSolutionManagerService,
          useValue: {
            displayHint: jasmine.createSpy('displayHint'),
          },
        },
        PlayerPositionService,
        {
          provide: PlayerTranscriptService,
          useValue: {
            getCard: () =>
              new StateCard(
                'test_name',
                'content',
                'interaction',
                {} as Interaction,
                [],
                'content_id'
              ),
          },
        },
        {
          provide: VoiceoverPlayerService,
          useValue: {
            setActiveVoiceover: jasmine.createSpy('setActiveVoiceover'),
            setActiveComponentName: jasmine.createSpy('setActiveComponentName'),
            getActiveVoiceover: jasmine.createSpy('getActiveVoiceover'),
          },
        },
        {
          provide: AudioBarStatusService,
          useValue: {
            isAudioBarExpanded: jasmine.createSpy('isAudioBarExpanded'),
          },
        },
      ],
      schemas: [NO_ERRORS_SCHEMA],
    }).compileComponents();
  }));

  beforeEach(() => {
    fixture = TestBed.createComponent(DisplayHintModalComponent);
    componentInstance = fixture.componentInstance;
    hintsAndSolutionManagerService = TestBed.inject(
      HintsAndSolutionManagerService
    );
    playerTranscriptService = TestBed.inject(PlayerTranscriptService);
    audioPlayerService = TestBed.inject(AudioPlayerService);
    autogeneratedAudioPlayerService = TestBed.inject(
      AutogeneratedAudioPlayerService
    );
    ngbActiveModal = TestBed.inject(NgbActiveModal);
    voiceoverPlayerService = TestBed.inject(VoiceoverPlayerService);
    audioBarStatusService = TestBed.inject(AudioBarStatusService);
    componentInstance.index = 0;
  });

  it('should create', () => {
    expect(componentInstance).toBeDefined();
  });

  it('should intialize', () => {
    let contentId: string = 'content_id';
    let hint = new SubtitledHtml('html', contentId);
    let displayedCard = new StateCard(
      'test_name',
      'content',
      'interaction',
      {} as Interaction,
      [],
      contentId
    );
    hintsAndSolutionManagerService.displayHint.and.returnValue(hint);
    spyOn(playerTranscriptService, 'getCard').and.returnValue(displayedCard);

    componentInstance.ngOnInit();

    expect(componentInstance.hint).toEqual(hint);
    expect(componentInstance.displayedCard).toEqual(displayedCard);
    expect(componentInstance.hintContentId).toEqual(contentId);
    expect(voiceoverPlayerService.setActiveVoiceover).toHaveBeenCalledWith(
      contentId
    );
    expect(voiceoverPlayerService.setActiveComponentName).toHaveBeenCalledWith(
      AppConstants.COMPONENT_NAME_HINT
    );
  });

  it('should throw error if display hint is invalid', () => {
    hintsAndSolutionManagerService.displayHint.and.returnValue(null);

    expect(() => {
      componentInstance.ngOnInit();
    }).toThrowError('Hint not found.');
  });

  it('should throw error if content id is invalid', () => {
    let contentId: string = 'content_id';
    let hint = new SubtitledHtml('html', null);
    let displayedCard = new StateCard(
      'test_name',
      'content',
      'interaction',
      {} as Interaction,
      [],
      contentId
    );
    hintsAndSolutionManagerService.displayHint.and.returnValue(hint);
    spyOn(playerTranscriptService, 'getCard').and.returnValue(displayedCard);

    expect(() => {
      componentInstance.ngOnInit();
    }).toThrowError('Content id not found.');
  });

  it('should check if audio bar is expanded', () => {
    audioBarStatusService.isAudioBarExpanded.and.returnValue(true);
    expect(componentInstance.isAudioBarExpanded()).toBe(true);

    audioBarStatusService.isAudioBarExpanded.and.returnValue(false);
    expect(componentInstance.isAudioBarExpanded()).toBe(false);
  });

  describe('playVoiceover', () => {
    beforeEach(() => {
      componentInstance.hasVoiceover = true;
      voiceoverPlayerService.getActiveVoiceover.and.returnValue({
        filename: 'test.mp3',
      });
    });

    it('should stop and clear audio when already playing', () => {
      componentInstance.isPlaying = true;
      componentInstance.playVoiceover();

      expect(audioPlayerService.stop).toHaveBeenCalled();
      expect(audioPlayerService.clear).toHaveBeenCalled();
      expect(componentInstance.isPlaying).toBe(false);
    });

    it('should load and play audio when not playing', fakeAsync(() => {
      componentInstance.isPlaying = false;
      componentInstance.playVoiceover();
      tick();

      expect(audioPlayerService.stop).toHaveBeenCalled();
      expect(audioPlayerService.clear).toHaveBeenCalled();
      expect(audioPlayerService.loadAsync).toHaveBeenCalledWith('test.mp3');
      expect(audioPlayerService.setCurrentTime).toHaveBeenCalledWith(0);
      expect(audioPlayerService.play).toHaveBeenCalled();
      expect(componentInstance.isPlaying).toBe(true);
    }));
  });

  it('should handle audio stop event', () => {
    let hint = new SubtitledHtml('html', 'content_id');
    hintsAndSolutionManagerService.displayHint.and.returnValue(hint);
    componentInstance.ngOnInit();
    componentInstance.isPlaying = true;
    (audioPlayerService.onAudioStop as EventEmitter<void>).emit();
    fixture.detectChanges();
    expect(componentInstance.isPlaying).toBe(false);
  });

  it('should handle audio end event', () => {
    let hint = new SubtitledHtml('html', 'content_id');
    hintsAndSolutionManagerService.displayHint.and.returnValue(hint);
    componentInstance.ngOnInit();
    componentInstance.isPlaying = true;
    (audioPlayerService.onAudioEnd as EventEmitter<void>).emit();
    fixture.detectChanges();
    expect(componentInstance.isPlaying).toBe(false);
  });

  it('should close modal', () => {
    spyOn(ngbActiveModal, 'dismiss');
    componentInstance.closeModal();
    expect(audioPlayerService.stop).toHaveBeenCalled();
    expect(autogeneratedAudioPlayerService.cancel).toHaveBeenCalled();
    expect(ngbActiveModal.dismiss).toHaveBeenCalledWith('cancel');
  });
});
