/**
 * @fileoverview Tests for the auto-translation confirmation modal.
 */

import {ComponentFixture, TestBed} from '@angular/core/testing';
import {NO_ERRORS_SCHEMA} from '@angular/core';
import {MatBottomSheetRef} from '@angular/material/bottom-sheet';
import {NgbActiveModal} from '@ng-bootstrap/ng-bootstrap';
import {Subject} from 'rxjs';
import {MockTranslatePipe} from 'tests/unit-test-utils';

import {AutoTranslationConfirmationModalComponent} from './auto-translation-confirmation-modal.component';

describe('AutoTranslationConfirmationModalComponent', () => {
  let component: AutoTranslationConfirmationModalComponent;
  let fixture: ComponentFixture<AutoTranslationConfirmationModalComponent>;
  let activeModal: NgbActiveModal;

  beforeEach(async () => {
    await TestBed.configureTestingModule({
      declarations: [
        AutoTranslationConfirmationModalComponent,
        MockTranslatePipe,
      ],
      providers: [NgbActiveModal, {provide: MatBottomSheetRef, useValue: null}],
      schemas: [NO_ERRORS_SCHEMA],
    }).compileComponents();

    fixture = TestBed.createComponent(
      AutoTranslationConfirmationModalComponent
    );
    component = fixture.componentInstance;
    activeModal = TestBed.inject(NgbActiveModal);
  });

  it('should close while keeping the current translation', () => {
    spyOn(activeModal, 'close');

    component.keepMine();

    expect(activeModal.close).toHaveBeenCalledWith('keep');
  });

  it('should close while replacing with the generated translation', () => {
    spyOn(activeModal, 'close');

    component.replaceWithAutoGenerated();

    expect(activeModal.close).toHaveBeenCalledWith('replace');
  });

  it('should return the selected action when opened as a bottom sheet', () => {
    const bottomSheetRef = jasmine.createSpyObj<
      MatBottomSheetRef<AutoTranslationConfirmationModalComponent>
    >('MatBottomSheetRef', ['dismiss', 'keydownEvents']);
    bottomSheetRef.keydownEvents.and.returnValue(
      new Subject<KeyboardEvent>().asObservable()
    );
    const bottomSheetComponent = new AutoTranslationConfirmationModalComponent(
      activeModal,
      bottomSheetRef
    );

    bottomSheetComponent.keepMine();
    bottomSheetComponent.replaceWithAutoGenerated();

    expect(bottomSheetRef.dismiss).toHaveBeenCalledWith('keep');
    expect(bottomSheetRef.dismiss).toHaveBeenCalledWith('replace');
  });

  it('should display the current and generated translations', () => {
    component.currentTranslation = '<p>My text</p>';
    component.autoGeneratedTranslation = '<p>Generated text</p>';
    fixture.detectChanges();

    const comparisonPanels = fixture.nativeElement.querySelectorAll(
      '.oppia-auto-translation-comparison-panel'
    );
    expect(comparisonPanels.length).toBe(2);
    expect(comparisonPanels[0].textContent).toContain(
      'I18N_MODAL_REPLACE_TRANSLATION_CURRENT_TEXT'
    );
    expect(comparisonPanels[1].textContent).toContain(
      'I18N_MODAL_REPLACE_TRANSLATION_AUTO_GENERATED_TEXT'
    );
  });
});
