/**
 * @fileoverview Modal for confirming replacement of an existing translation.
 */

import {Component, Input, Optional} from '@angular/core';
import {MatBottomSheetRef} from '@angular/material/bottom-sheet';
import {NgbActiveModal} from '@ng-bootstrap/ng-bootstrap';
import {ConfirmOrCancelModal} from 'components/common-layout-directives/common-elements/confirm-or-cancel-modal.component';

@Component({
  selector: 'oppia-auto-translation-confirmation-modal',
  templateUrl: './auto-translation-confirmation-modal.component.html',
  styleUrls: ['./auto-translation-confirmation-modal.component.css'],
})
export class AutoTranslationConfirmationModalComponent extends ConfirmOrCancelModal {
  @Input() currentTranslation: string = '';
  @Input() autoGeneratedTranslation: string = '';

  constructor(
    @Optional() ngbActiveModal: NgbActiveModal,
    @Optional()
    bottomSheetRef?: MatBottomSheetRef<AutoTranslationConfirmationModalComponent>
  ) {
    super(ngbActiveModal, bottomSheetRef);
  }

  keepMine(): void {
    super.confirm('keep');
  }

  replaceWithAutoGenerated(): void {
    super.confirm('replace');
  }
}
