"""Domain objects relating to recommendations."""

from __future__ import annotations

import re

from core import utils
from core.constants import constants

from typing import List, TypedDict


class ExplorationRecommendationsDict(TypedDict):
    """Dictionary representation of an ExplorationRecommendations domain
    object.
    """

    exploration_id: str
    recommended_exploration_ids: List[str]


class ExplorationRecommendations:
    """Domain object for the explorations that are recommended to be played
    after a given exploration.
    """

    def __init__(
        self, exploration_id: str, recommended_exploration_ids: List[str]
    ) -> None:
        """Constructs an ExplorationRecommendations domain object.

        Args:
            exploration_id: str. The ID of the exploration that the
                recommendations are for.
            recommended_exploration_ids: list(str). The IDs of the explorations
                recommended to be played after the exploration with ID
                exploration_id.
        """
        self.exploration_id = exploration_id
        self.recommended_exploration_ids = recommended_exploration_ids

    @classmethod
    def require_valid_exploration_id(
        cls, exploration_id: str, field_name: str
    ) -> None:
        """Checks whether the given exploration ID is a valid one.

        Args:
            exploration_id: str. The exploration ID to validate.
            field_name: str. The name of the field the ID was read from, used
                to make the error message point at the offending field.

        Raises:
            ValidationError. The exploration ID is empty or contains characters
                that are not allowed in an entity ID.
        """
        if not exploration_id:
            raise utils.ValidationError('%s should not be empty.' % field_name)

        if not re.match(constants.ENTITY_ID_REGEX, exploration_id):
            raise utils.ValidationError(
                '%s contains invalid characters. Only words consisting of '
                'alphanumeric characters, hyphens (-) and underscores (_), '
                'and at most 12 characters long, are allowed. Received %s.'
                % (field_name, exploration_id)
            )

    def validate(self) -> None:
        """Checks that all fields of this ExplorationRecommendations domain
        object are valid.

        Note that the number of recommendations is deliberately not validated.
        The cap of 10 is applied when the recommendations are generated by the
        batch job, and enforcing it here would reject legacy datastore entities
        that already store more than that.

        Raises:
            ValidationError. One or more fields of this domain object are
                invalid.
        """
        self.require_valid_exploration_id(self.exploration_id, 'Exploration id')

        for recommended_exploration_id in self.recommended_exploration_ids:
            self.require_valid_exploration_id(
                recommended_exploration_id, 'Recommended exploration id'
            )

        if len(set(self.recommended_exploration_ids)) != len(
            self.recommended_exploration_ids
        ):
            raise utils.ValidationError(
                'Recommended exploration ids should not contain duplicates. '
                'Received %s.' % self.recommended_exploration_ids
            )

        if self.exploration_id in self.recommended_exploration_ids:
            raise utils.ValidationError(
                'Exploration %s should not be recommended after itself.'
                % self.exploration_id
            )

    def to_dict(self) -> ExplorationRecommendationsDict:
        """Returns a dict representing this ExplorationRecommendations domain
        object.

        Returns:
            dict. A dict, mapping all the fields of this domain object to their
            corresponding keys.
        """
        return {
            'exploration_id': self.exploration_id,
            'recommended_exploration_ids': self.recommended_exploration_ids,
        }

    @classmethod
    def from_dict(
        cls, exploration_recommendations_dict: ExplorationRecommendationsDict
    ) -> ExplorationRecommendations:
        """Returns an ExplorationRecommendations domain object from the given
        dict.

        Args:
            exploration_recommendations_dict: dict. The dict representation of
                an ExplorationRecommendations object.

        Returns:
            ExplorationRecommendations. The corresponding domain object.
        """
        return cls(
            exploration_recommendations_dict['exploration_id'],
            exploration_recommendations_dict['recommended_exploration_ids'],
        )
