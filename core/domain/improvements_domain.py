"""Domain objects related to Oppia improvement tasks."""

from __future__ import annotations

import datetime
import re

from core import feconf, utils
from core.constants import constants

from typing import Final, Optional, TypedDict

# The values a TaskEntry may take for each of its enumerated fields. These
# mirror the `choices` declared on ExplorationStatsTaskEntryModel, and are
# built from constants here so that the domain layer does not import storage.
ALLOWED_ENTITY_TYPES: Final = (constants.TASK_ENTITY_TYPE_EXPLORATION,)
ALLOWED_TARGET_TYPES: Final = (constants.TASK_TARGET_TYPE_STATE,)
ALLOWED_TASK_TYPES: Final = (
    constants.TASK_TYPE_HIGH_BOUNCE_RATE,
    constants.TASK_TYPE_INEFFECTIVE_FEEDBACK_LOOP,
    constants.TASK_TYPE_SUCCESSIVE_INCORRECT_ANSWERS,
    constants.TASK_TYPE_NEEDS_GUIDING_RESPONSES,
)
ALLOWED_STATUSES: Final = (
    constants.TASK_STATUS_OPEN,
    constants.TASK_STATUS_OBSOLETE,
    constants.TASK_STATUS_RESOLVED,
)


class TaskEntryDict(TypedDict):
    """Dict for TaskEntry object."""

    entity_type: str
    entity_id: str
    entity_version: int
    task_type: str
    target_type: str
    target_id: str
    issue_description: Optional[str]
    status: str
    resolver_username: Optional[str]
    resolved_on_msecs: Optional[float]


class TaskEntry:
    """Domain object representing an actionable task from the improvements tab.

    Attributes:
        entity_type: str. The type of entity the task entry refers to.
            For example, "exploration".
        entity_id: str. The ID of the entity the task entry refers to.
            For example, an exploration ID.
        entity_version: int. The version of the entity the task entry refers to.
            For example, an exploration's version.
        task_type: str. The type of task the task entry tracks.
        target_type: str. The type of sub-entity the task entry refers to.
            For example, "state" when entity type is "exploration".
        target_id: str. The ID of the sub-entity the task entry refers to.
            For example, the state name of an exploration.
        issue_description: str or None. The sentence generated by Oppia to
            describe why the task was created.
        status: str. Tracks the state/progress of the task entry.
        resolver_id: str or None. The corresponding user who resolved this task.
        resolved_on: datetime or None. The datetime at which this task was
            resolved.
    """

    def __init__(
        self,
        entity_type: str,
        entity_id: str,
        entity_version: int,
        task_type: str,
        target_type: str,
        target_id: str,
        issue_description: Optional[str],
        status: str,
        resolver_id: Optional[str] = None,
        resolved_on: Optional[datetime.datetime] = None,
    ) -> None:
        """Initializes a new TaskEntry domain object from the given values.

        Args:
            entity_type: str. The type of entity the task entry refers to.
                For example: "exploration".
            entity_id: str. The ID of the entity the task entry refers to.
                For example: an exploration ID.
            entity_version: int. The version of the entity the task entry refers
                to. For example: an exploration's version.
            task_type: str. The type of task the task entry tracks.
            target_type: str. The type of sub-entity the task entry refers to.
                For example, when entity type is "exploration": "state".
            target_id: str. The ID of the sub-entity the task entry refers to.
                For example, the state name of an exploration.
            issue_description: str. The sentence generated by Oppia to describe
                why the task was created.
            status: str. Tracks the state/progress of the task entry.
            resolver_id: str. The corresponding user who resolved this task.
                Only used when status is resolved, otherwise replaced with None.
            resolved_on: datetime. The datetime at which this task was resolved.
                Only used when status is resolved, otherwise replaced with None.
        """
        if status != constants.TASK_STATUS_RESOLVED:
            resolver_id = None
            resolved_on = None
        self.entity_type = entity_type
        self.entity_id = entity_id
        self.entity_version = entity_version
        self.task_type = task_type
        self.target_type = target_type
        self.target_id = target_id
        self.issue_description = issue_description
        self.status = status
        self.resolver_id = resolver_id
        self.resolved_on = resolved_on

    @property
    def task_id(self) -> str:
        """Returns the unique identifier of this task.

        Value has the form: "[entity_type].[entity_id].[entity_version].
                             [task_type].[target_type].[target_id]"

        Returns:
            str. The ID of this task.
        """
        return feconf.TASK_ENTRY_ID_TEMPLATE % (
            self.entity_type,
            self.entity_id,
            self.entity_version,
            self.task_type,
            self.target_type,
            self.target_id,
        )

    @property
    def composite_entity_id(self) -> str:
        """Utility field which results in a 20% speedup compared to querying by
        each of the invididual fields used to compose it.

        Value has the form: "[entity_type].[entity_id].[entity_version]".

        Returns:
            str. The value of the utility field.
        """
        return feconf.COMPOSITE_ENTITY_ID_TEMPLATE % (
            self.entity_type,
            self.entity_id,
            self.entity_version,
        )

    def validate(self) -> None:
        """Validates the properties of the TaskEntry.

        composite_entity_id and task_id are not checked here: both are derived
        from the fields below, so they cannot drift from them within the
        domain object. Their stored copies are checked by the Beam audit jobs.

        Raises:
            ValidationError. One or more attributes of the TaskEntry are
                invalid.
        """
        if self.entity_type not in ALLOWED_ENTITY_TYPES:
            raise utils.ValidationError(
                'Invalid entity_type: %s, expected one of %s.'
                % (self.entity_type, ALLOWED_ENTITY_TYPES)
            )

        if not re.match(constants.ENTITY_ID_REGEX, self.entity_id):
            raise utils.ValidationError(
                'Invalid entity_id: %s.' % self.entity_id
            )

        if self.entity_version < 1:
            raise utils.ValidationError(
                'Expected entity_version to be at least 1, received %s.'
                % self.entity_version
            )

        if self.task_type not in ALLOWED_TASK_TYPES:
            raise utils.ValidationError(
                'Invalid task_type: %s, expected one of %s.'
                % (self.task_type, ALLOWED_TASK_TYPES)
            )

        if self.target_type not in ALLOWED_TARGET_TYPES:
            raise utils.ValidationError(
                'Invalid target_type: %s, expected one of %s.'
                % (self.target_type, ALLOWED_TARGET_TYPES)
            )

        if not self.target_id:
            raise utils.ValidationError('Expected target_id to be non-empty.')

        if self.issue_description is not None and not self.issue_description:
            raise utils.ValidationError(
                'Expected issue_description to be None or non-empty.'
            )

        if self.status not in ALLOWED_STATUSES:
            raise utils.ValidationError(
                'Invalid status: %s, expected one of %s.'
                % (self.status, ALLOWED_STATUSES)
            )

        if self.status == constants.TASK_STATUS_RESOLVED:
            if self.resolver_id is None:
                raise utils.ValidationError(
                    'Expected a resolved task to have a resolver_id.'
                )
            # Wipeout replaces resolver_id with a pseudonymous ID, so those
            # must stay valid for the task to be saved again.
            if not utils.is_user_id_valid(
                self.resolver_id, allow_pseudonymous_id=True
            ):
                raise utils.ValidationError(
                    'Invalid resolver_id: %s.' % self.resolver_id
                )
            if self.resolved_on is None:
                raise utils.ValidationError(
                    'Expected a resolved task to have a resolved_on time.'
                )
        else:
            if self.resolver_id is not None or self.resolved_on is not None:
                raise utils.ValidationError(
                    'Expected a task with status %s to have no resolver_id '
                    'or resolved_on.' % self.status
                )

    def to_dict(self) -> TaskEntryDict:
        """Returns a dict-representation of the task.

        Returns:
            dict. Contains the following keys:
                entity_type: str. The type of entity the task entry refers to.
                    For example, "exploration".
                entity_id: str. The ID of the entity the task entry refers to.
                    For example, an exploration ID.
                entity_version: int. The version of the entity the task entry
                    refers to. For example, an exploration's version.
                task_type: str. The type of task the task entry tracks.
                target_type: str. The type of sub-entity the task entry refers
                    to. For example, "state" when entity type is "exploration".
                target_id: str. The ID of the sub-entity the task entry refers
                    to. For example, the state name of an exploration.
                issue_description: str. The sentence generated by Oppia to
                    describe why the task was created.
                status: str. Tracks the state/progress of the task entry.
                resolver_username: str|None. Username of the user who resolved
                    the task when status is resolved. Otherwise None.
                resolved_on_msecs: float|None. Time in
                    milliseconds since epoch at which the task was resolved
                    when status is resolved. Otherwise None.
        """

        return {
            'entity_type': self.entity_type,
            'entity_id': self.entity_id,
            'entity_version': self.entity_version,
            'task_type': self.task_type,
            'target_type': self.target_type,
            'target_id': self.target_id,
            'issue_description': self.issue_description,
            'status': self.status,
            'resolver_username': None,
            'resolved_on_msecs': (
                None
                if not self.resolved_on
                else utils.get_time_in_millisecs(self.resolved_on)
            ),
        }
